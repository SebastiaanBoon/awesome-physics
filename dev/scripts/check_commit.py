"""Check a commit message against the Conventional Commits style.

Usage:
    python3 dev/scripts/check_commit.py COMMIT_MSG_FILE
    printf '%s\n' "feat(readme): add QuTiP" | python3 dev/scripts/check_commit.py -

The file is the one Git passes to the ``commit-msg`` hook. Comment lines
starting with ``#`` (the ``.gitmessage`` template) are ignored.

Exit status is 0 for a valid message, 1 for a style error, and 2 for usage or
I/O errors.
"""
from __future__ import annotations

import re
import sys

TYPES = (
    "feat",
    "fix",
    "docs",
    "style",
    "refactor",
    "perf",
    "test",
    "build",
    "ci",
    "chore",
    "revert",
)

# Merge commits, reverts, and autosquash markers are generated by Git itself.
EXEMPT_PREFIXES = ("Merge ", "Revert ", "fixup! ", "squash! ", "amend! ")

HEADER = re.compile(
    r"^(?:" + "|".join(TYPES) + r")"
    r"(?:\([a-z0-9._/-]+\))?"
    r": \S.*$"
)

MAX_HEADER = 72


def read_message(path: str) -> list[str]:
    """Return the message lines without comments or trailing blank lines."""
    if path == "-":
        text = sys.stdin.read()
    else:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()

    lines = [line.rstrip() for line in text.splitlines() if not line.startswith("#")]
    while lines and not lines[-1]:
        lines.pop()
    return lines


def check(lines: list[str]) -> list[str]:
    """Return a list of style errors (empty when the message is valid)."""
    if not lines:
        return []

    header = lines[0]
    if header.startswith(EXEMPT_PREFIXES):
        return []

    errors: list[str] = []
    if not HEADER.match(header):
        errors.append(
            "expected '<type>(<scope>): <subject>' with a known type"
        )
        return errors

    if len(header) > MAX_HEADER:
        errors.append(
            f"keep the header within {MAX_HEADER} characters (got {len(header)})"
        )

    if header.endswith("."):
        errors.append("do not end the subject with a period")

    subject = header.split(": ", 1)[1]
    if subject[:1].isupper():
        errors.append("start the subject in lowercase (imperative mood)")

    if len(lines) > 1 and lines[1]:
        errors.append("leave a blank line between the subject and the body")

    return errors


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: check_commit.py <message-file|->", file=sys.stderr)
        return 2

    try:
        lines = read_message(argv[1])
    except OSError as error:
        print(f"check_commit: {error}", file=sys.stderr)
        return 2

    errors = check(lines)
    if not errors:
        return 0

    print("check_commit: commit message does not follow Conventional Commits\n", file=sys.stderr)
    for error in errors:
        print(f"  - {error}", file=sys.stderr)
    if lines:
        print(f"\n  got: {lines[0]}\n", file=sys.stderr)
    print("  format: <type>(<scope>): <subject>", file=sys.stderr)
    print(f"  types:  {', '.join(TYPES)}", file=sys.stderr)
    print("  guide:  CONTRIBUTING.md#commit-messages", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
